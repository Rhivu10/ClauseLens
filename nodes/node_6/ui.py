"""
ClauseLens — Node 6
Data for the ClauseLens UI (clauselens-ui: React + Vite, run with Node.js).

The UI reads three things from src/data/mockData.js:

    documents   {document_a: {document_id, label, chunk_count, page_count, ...}, document_b: {...}}
    chunks      {document_a: [{chunk_id, text, page_start, page_end, heading_path}], document_b: [...]}
    alignments  [{id, status, score, a, b, note}]
                status: "match" | "diverge" | "missing_in_a" | "missing_in_b"

to_ui_data() turns a Node 6 report into exactly that shape, so the real results
can replace the mock data without changing the UI. Each alignment also carries
the Node 6 details (confidence, needs_review, affected parties, duty shift,
highlight offsets); the current UI ignores them, a later version can use them.
"""

from __future__ import annotations

import json
import os
from typing import Any

# Node 6 change type -> UI alignment status
UI_STATUS = {
    "MODIFIED": "diverge",
    "ADDED": "missing_in_a",       # only in the new version  -> "New in v4"
    "DELETED": "missing_in_b",     # only in the old version  -> "Dropped in v4"
    "UNVERIFIED": "missing_in_b",  # old clause, no confirmed match in the new version
}


def _ui_chunk(e: dict[str, Any]) -> dict[str, Any]:
    pages = list(e.get("pages") or []) + [None, None]
    start, end = pages[0], pages[1]
    return {
        "chunk_id": e["chunk_id"],
        "text": e.get("text", ""),
        "page_start": start,
        "page_end": end if end is not None else start,
        "heading_path": e.get("heading_path") or [],
        # Extra: offsets of the changed sentences inside `text`, for highlighting
        "highlights": e.get("highlights", []),
    }


def to_ui_data(report: dict[str, Any]) -> dict[str, Any]:
    """{"documents", "chunks", "alignments", "overview"} in the clauselens-ui mockData shape."""
    documents = {}
    for doc_id, d in report["documents"].items():
        documents[doc_id] = {
            "document_id": doc_id,
            "label": d.get("name") or doc_id,
            "source_path": None,
            "element_count": None,
            "chunk_count": d.get("chunks"),
            "page_count": d.get("pages"),
        }

    chunks: dict[str, list[dict[str, Any]]] = {doc_id: [] for doc_id in documents}
    seen: set[str] = set()
    alignments = []
    for c in report["changes"]:
        old, new = c["evidence"]["old"], c["evidence"]["new"]
        for e in (old, new):
            if e and e["chunk_id"] not in seen:
                seen.add(e["chunk_id"])
                chunks.setdefault(e["document_id"], []).append(_ui_chunk(e))
        alignments.append({
            "id": f"align_{c['id'][1:]}",                  # C003 -> align_003
            "status": UI_STATUS.get(c["type"], "diverge"),
            "score": c.get("similarity"),
            "a": old["chunk_id"] if old else None,
            "b": new["chunk_id"] if new else None,
            "note": c["summary"],
            # Node 6 details (not read by the current UI)
            "change_id": c["id"],
            "type": c["type"],
            "title": c["title"],
            "section": c["section"],
            "confidence": c["confidence"],
            "needs_review": c["needs_review"],
            "review_reason": c["review_reason"],
            "affected": c["affected"],
            "duty_shift": c["duty"]["shift"],
            "numbers": c["numbers"],
        })

    for doc_id in chunks:                                  # stable order for the UI
        chunks[doc_id].sort(key=lambda ch: ch["chunk_id"])
    return {"documents": documents, "chunks": chunks, "alignments": alignments,
            "overview": report["overview"]}


def save_ui_data(report: dict[str, Any], path: str) -> str:
    """The UI data as JSON (for a backend endpoint the UI fetches)."""
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(to_ui_data(report), fh, ensure_ascii=False, indent=2)
    return path


def save_ui_module(report: dict[str, Any], path: str) -> str:
    """
    The UI data as a JavaScript module with the same exports as
    clauselens-ui/src/data/mockData.js (documents, chunks, alignments), so it can
    replace that file directly. sampleRetrieval / sampleConversation are kept as
    empty lists so the Consult page still imports.
    """
    data = to_ui_data(report)
    dump = lambda v: json.dumps(v, ensure_ascii=False, indent=2)
    js = (
        "// Generated by ClauseLens Node 6 (to_ui_data) from a real report.\n"
        "// Drop-in replacement for src/data/mockData.js.\n\n"
        f"export const documents = {dump(data['documents'])};\n\n"
        f"export const chunks = {dump(data['chunks'])};\n\n"
        f"export const alignments = {dump(data['alignments'])};\n\n"
        f"export const overview = {dump(data['overview'])};\n\n"
        "export const sampleRetrieval = [];\n\n"
        "export const sampleConversation = [];\n"
    )
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(js)
    return path
