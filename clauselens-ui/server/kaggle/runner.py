import re
from typing import Any

_NOISE_LINE = re.compile(
    r"^\s*(?:"
    r"\d{1,2}/\d{1,2}/\d{2,4},?\s+\d{1,2}:\d{2}\s*(?:AM|PM)?"   # 10/18/26, 1:14 PM
    r"|https?://\S+"                                             # page URL
    r"|ex[\w.\-]*?(?:\.htm)?"                                    # exv10w1, ex10-2.htm
    r"|\d{1,3}\s*/\s*\d{1,3}"                                    # 2/23
    r"|-?\s*\d{1,3}\s*-?"                                        # 4, -1-
    r"|EX-\d+(?:\.\d+)?\s+\d+\s+\S+\.htm\b.*"                    # EX-10.1 2 w74314exv10w1.htm EXHIBIT 10.1
    r")\s*$",
    re.I,
)

# “Territory” means ... / "Term" shall have the meaning ...
_DEF_START = re.compile(r"^\s*[“\"]([^”\"]{1,80})[”\"]\s+(?:means|has the meaning|shall mean|shall have)", re.I)

# "11.Insurance.", "17. Complete Agreement.", "26.Use of Name.Licensor ..." (top-level
# section with a short title; the text may follow the title without a space)
_SECTION_START = re.compile(r"^\s*(\d{1,2})\.\s*([A-Z][A-Za-z;,’'&\- ]{2,60}?)\.(?:\s|$|(?=[A-Z]))")

# "2.1 ", "10.3\xa0" (numbered subsection)
_SUBSECTION_START = re.compile(r"^\s*\d{1,2}\.\d{1,2}[\s\xa0]")


def _clean_text(text: str) -> str:
    return "\n".join(l for l in text.splitlines() if not _NOISE_LINE.match(l))


def _split_long(text: str, max_chars: int) -> list[tuple[str, str | None]]:
    """[(piece_text, heading_or_None)] for one long chunk."""
    lines = text.splitlines()
    pieces: list[tuple[list[str], str | None]] = []

    if sum(1 for l in lines if _DEF_START.match(l)) >= 3:
        # Definitions: one piece per definition, headed by the defined term
        for l in lines:
            m = _DEF_START.match(l)
            if m or not pieces:
                pieces.append(([], f"“{m.group(1)}”" if m else None))
            pieces[-1][0].append(l)
    else:
        # Numbered sections and subsections start a new piece
        for l in lines:
            sec = _SECTION_START.match(l)
            if pieces and (sec or _SUBSECTION_START.match(l)):
                pieces.append(([], f"{sec.group(1)}. {sec.group(2).strip()}." if sec else None))
            elif not pieces:
                pieces.append(([], f"{sec.group(1)}. {sec.group(2).strip()}." if sec else None))
            pieces[-1][0].append(l)

    # Anything still too long: split at line boundaries
    out: list[tuple[str, str | None]] = []
    for plines, head in pieces:
        cur, n = [], 0
        for l in plines:
            if cur and n + len(l) > max_chars:
                out.append(("\n".join(cur), head))
                cur, n = [], 0
            cur.append(l)
            n += len(l) + 1
        if cur:
            out.append(("\n".join(cur), head))
    return [(t, h) for t, h in out if t.strip()]


_SENTENCE_END = re.compile(r"""[.;:!?]["'”’)\]]*\s*$""")


def _is_caps_line(line: str) -> bool:
    letters = [ch for ch in line if ch.isalpha()]
    return len(letters) >= 12 and sum(ch.isupper() for ch in letters) / len(letters) > 0.9


def _split_caps_blocks(text: str, head: str | None) -> list[tuple[str, str | None]]:
    """
    Split where an ALL-CAPS paragraph (4+ words) starts right after a finished
    sentence, and where normal text starts right after an ALL-CAPS paragraph ends.
    On the Apache License, the warranty disclaimer and the closing note were glued
    to the last numbered condition, so "6. ... + disclaimer" matched "5. ... +
    disclaimer" in the other version. A split-off piece is headed by its first words.
    """
    lines = text.splitlines()
    pieces: list[tuple[list[str], str | None]] = [([], head)]
    caps_words = 0                      # words in the ALL-CAPS lines just before this line
    for i, line in enumerate(lines):
        prev = lines[i - 1] if i else ""
        caps, prev_caps = _is_caps_line(line), _is_caps_line(prev)
        starts_caps = caps and not prev_caps and len(line.split()) >= 4 and _SENTENCE_END.search(prev)
        # only after a real paragraph: a party name like "ECHO THERAPEUTICS, INC." in a
        # signature block is not a block of its own
        ends_caps = prev_caps and not caps and line.strip() and _SENTENCE_END.search(prev) and caps_words >= 8
        caps_words = caps_words + len(line.split()) if caps else 0
        if pieces[-1][0] and (starts_caps or ends_caps):
            first = " ".join(line.split()[:8])
            pieces.append(([], first[:60]))
        pieces[-1][0].append(line)
    return [("\n".join(p), h) for p, h in pieces if "".join(p).strip()]


def clean_chunks(
    result: dict[str, Any],
    max_chars: int = 1500,
    min_chars: int = 40,
) -> dict[str, dict[str, int]]:
    """
    Clean the chunks of a process_documents() result in place and return stats.

    Chunk ids stay unique: a split chunk keeps its id with a suffix
    (document_a_0009_32); a merged fragment's text joins the next chunk's id.
    """
    stats = {}
    for doc_id, d in result.items():
        removed = split = merged = 0
        pieces: list[dict[str, Any]] = []

        # 1 + 2: drop noise lines, split long chunks
        for c in d["chunks"]:
            text = _clean_text(c["text"])
            if not text.strip():
                removed += 1
                continue
            # Long chunks are split; so is any chunk holding more than one numbered
            # section ("10. Indemnity. ... 11.Insurance. ..."), whatever its length,
            # because that means Node 1 missed a heading
            extra_sections = sum(1 for l in text.splitlines()[1:] if _SECTION_START.match(l))
            if len(text) > max_chars or extra_sections:
                parts = _split_long(text, max_chars)
            else:
                parts = [(text, None)]
            # ALL-CAPS paragraphs (warranty / liability disclaimers) and the text after
            # them are their own clauses, not part of the clause before
            parts = [q for part, head in parts for q in _split_caps_blocks(part, head)]
            split += len(parts) > 1
            for k, (part, head) in enumerate(parts):
                path = list(c.get("heading_path") or [])
                if head:
                    path = (path[:-1] if len(parts) > 1 and path else path) + [head]
                pieces.append({
                    **c,
                    "chunk_id": c["chunk_id"] if len(parts) == 1 else f"{c['chunk_id']}_{k + 1:02d}",
                    "text": part,
                    "heading_path": path,
                })

        # 3: merge tiny fragments into the following chunk
        out: list[dict[str, Any]] = []
        carry: dict[str, Any] | None = None
        for c in pieces:
            if carry is not None:
                c = {**c, "text": carry["text"] + "\n" + c["text"],
                     "page_start": min(carry.get("page_start", c.get("page_start")), c.get("page_start"))}
                carry = None
            if len(c["text"].strip()) < min_chars:
                carry = c
                merged += 1
                continue
            out.append(c)
        if carry is not None:                       # a fragment at the very end joins the last chunk
            if out:
                out[-1] = {**out[-1], "text": out[-1]["text"] + "\n" + carry["text"]}
            else:
                out.append(carry)

        d["chunks"], d["chunk_count"] = out, len(out)
        stats[doc_id] = {"chunks": len(out), "noise_only_removed": removed,
                         "long_chunks_split": split, "tiny_chunks_merged": merged}
    return stats


def find_job():
    hits = glob.glob("/kaggle/input/**/clauselens_job.json", recursive=True)
    if not hits:
        raise FileNotFoundError("clauselens_job.json not found: attach the clauselens-input dataset.")
    path = hits[0]
    job = json.load(open(path, encoding="utf-8"))
    folder = os.path.dirname(path)
    for side in ("document_a", "document_b"):
        job[side]["path"] = os.path.join(folder, job[side]["file"])
        if not os.path.exists(job[side]["path"]):
            raise FileNotFoundError(f"{job[side]['file']} is missing from the clauselens-input dataset.")
    return job


def find_checkpoint():
    """The CUAD LoRA adapter: in the cloned repo, or an attached Kaggle dataset."""
    repo_copy = f"{REPO_PATH}/Model Finetuning/checkpoints/checkpoint-2091"
    if os.path.exists(f"{repo_copy}/adapter_model.safetensors"):
        return repo_copy
    hits = sorted(glob.glob("/kaggle/input/**/adapter_config.json", recursive=True),
                  key=lambda p: ("checkpoint-2091" not in p, p))
    if not hits:
        raise FileNotFoundError("CUAD LoRA adapter not found in the repo (Model Finetuning/checkpoints/"
                                "checkpoint-2091) or in an attached Kaggle dataset.")
    return os.path.dirname(hits[0])


def hf_token():
    try:
        from kaggle_secrets import UserSecretsClient
        return UserSecretsClient().get_secret("HF-Token")
    except Exception:
        return None                       # the unsloth/* models are public


def install_libraries():
    for step in PIP_STEPS:
        pip(*step)


def clone_repo(branch=REPO_BRANCH):
    os.makedirs(WORK, exist_ok=True)
    if os.path.exists(REPO_PATH):
        shutil.rmtree(REPO_PATH)
    sh("git", "clone", "-q", "--depth", "1", "-b", branch, REPO_URL, REPO_PATH)
    sys.path.insert(0, REPO_PATH)
    commit = subprocess.check_output(["git", "-C", REPO_PATH, "log", "--oneline", "-1"], text=True).strip()
    return commit


EMIT = {"seq": 0}


def emit_data(kind, obj):
    """Data for the live page, read from the log: base64 JSON in 8 KB lines."""
    obj = {"job_id": JOB["job_id"], **obj}            # the laptop ignores data from other runs
    blob = base64.b64encode(json.dumps(obj, ensure_ascii=False).encode("utf-8")).decode("ascii")
    parts = [blob[i:i + 8000] for i in range(0, len(blob), 8000)] or [""]
    EMIT["seq"] += 1
    for n, part in enumerate(parts, 1):
        print(f"[ClauseLensData {kind} {EMIT['seq']} {n}/{len(parts)}] {part}", flush=True)


PENDING = {"status": "PENDING", "confidence": None, "summary": "", "affected": [], "reason": "",
           "categories": [], "attempts": 0}


class LiveReport:
    """
    The report as it fills in: Node 6 built over the Node 5 results so far, with
    "PENDING" placeholders for the rest. Pairs Node 5 will skip (too little text)
    are skipped here too, so change ids (C001, ...) match the final report.
    """

    def __init__(self, documents, all_chunks, node3_report, pairs, skipped):
        from nodes.node_6 import ReportAssembler, to_ui_data
        self._assembler, self._to_ui = ReportAssembler, to_ui_data
        self.documents, self.all_chunks, self.node3_report, self.pairs = documents, all_chunks, node3_report, pairs
        self.results = {}
        for p in pairs:
            im = dict(PENDING, status="SKIPPED") if p["pair_id"] in skipped else dict(PENDING)
            self.results[p["pair_id"]] = {**p, "impact": im}
        self.total = len(pairs) - len(skipped)

    def ui(self):
        rep = self._assembler(documents=self.documents, all_chunks=self.all_chunks,
                              node3_report=self.node3_report).add_many(
            [self.results[p["pair_id"]] for p in self.pairs]).build()
        ui = self._to_ui(rep)
        for al, change in zip(ui["alignments"], rep["changes"]):
            al["pair_id"] = change["pair_id"]
            al["pending"] = change["status"] == "PENDING"
        return ui

    def done(self):
        return sum(1 for r in self.results.values() if r["impact"]["status"] not in ("PENDING", "SKIPPED"))

    def preview(self):
        emit_data("preview", {"ui": self.ui(), "done": 0, "total": self.total})

    def update(self, result):
        self.results[result["pair_id"]] = result
        if result["impact"]["status"] == "SKIPPED":
            return
        ui = self.ui()
        al = next((a for a in ui["alignments"] if a["pair_id"] == result["pair_id"]), None)
        emit_data("result", {"pair_id": result["pair_id"], "alignment": al, "overview": ui["overview"],
                             "done": self.done(), "total": self.total})


def run_node5(core, pairs, checkpoint, live):
    """core.run(), but every finished result also goes to the live page."""
    results, t0 = {}, time.time()
    for i, r in enumerate(core.iter_run(pairs, checkpoint), 1):
        results[r["pair_id"]] = r
        live.update(r)
        print(f"[{i}/{len(pairs)}] {r['impact']['status']:14} {r['pair_id']} "
              f"| attempts {r['impact']['attempts']} | elapsed {time.time() - t0:.0f}s", flush=True)
    ordered = [results[p["pair_id"]] for p in pairs]
    return {"results": ordered, "counts": dict(Counter(r["impact"]["status"] for r in ordered)),
            "seconds": round(time.time() - t0, 1)}


def run():
    job = find_job()
    JOB["job_id"] = job["job_id"]
    stage("started", files=[job["document_a"]["file"], job["document_b"]["file"]])

    stage("installing")
    install_libraries()
    commit = clone_repo(job.get("repo_branch") or REPO_BRANCH)
    print("ClauseLens commit:", commit)

    import unsloth  # noqa: F401  (must be imported before transformers / peft)
    import torch
    torch._dynamo.config.recompile_limit = 64
    gpus = torch.cuda.device_count()
    print("GPUs:", [torch.cuda.get_device_name(i) for i in range(gpus)])
    if gpus == 0:
        raise RuntimeError("No GPU: set the notebook accelerator to 'GPU T4 x2'.")

    from nodes.node_1 import process_documents
    from nodes.node_2 import prepare_chunks, Node2Indexer
    from nodes.node_3 import Node3Config, load_gemma_with_adapter, GemmaVerifier, Node3Aligner
    from nodes.node_4 import Node4Config, DeonticChecker, Node4Extractor
    from nodes.node_5 import (Node5Config, load_critic_model, load_agent_model, ImpactAgent,
                              CriticAgent, Node5ImpactCore, CRITIC_BASE_MODELS)
    from nodes.node_6 import ReportAssembler, save_report, save_markdown, save_ui_data

    token = hf_token()
    node3_config, node5_config = Node3Config(), Node5Config()
    out_dir = f"{WORK}/outputs"
    os.makedirs(out_dir, exist_ok=True)

    # Node 3 model (GPU 0): Gemma E2B + CUAD adapter
    stage("loading_models")
    model, tokenizer = load_gemma_with_adapter(find_checkpoint(), max_seq_length=node5_config.max_seq_length,
                                               hf_token=token)

    # Node 1 + clean-up + Node 2
    stage("node_1_2_parsing")
    result = process_documents(job["document_a"]["path"], job["document_b"]["path"],
                               start_new_chunk_on_level=2, max_chars=CHUNK_MAX_CHARS)
    print("Node 1  :", {d: r["chunk_count"] for d, r in result.items()})
    print("Clean-up:", clean_chunks(result, CHUNK_MAX_CHARS))
    all_chunks = prepare_chunks(result, version_ids={"document_a": "version_a", "document_b": "version_b"})
    indexer = Node2Indexer()
    index_bundle = indexer.build(all_chunks)
    stage("node_1_2_done", chunks={d: r["chunk_count"] for d, r in result.items()})

    # Node 3
    stage("node_3_alignment")
    verifier = GemmaVerifier(model, tokenizer, node3_config)
    aligner = Node3Aligner(all_chunks, index_bundle, indexer.embedding_model, verifier)
    report = aligner.align_documents("document_a", "document_b")
    print("Node 3 counts:", report["counts"])

    # Node 4
    stage("node_4_duties")
    extractor = Node4Extractor(all_chunks, DeonticChecker(model, tokenizer, Node4Config()))
    node4_output = extractor.run(report, checkpoint_path=f"{out_dir}/node4_pairs.jsonl")
    pairs = node4_output["pairs"]
    print("Node 4 changed pairs:", node4_output["counts"])

    # Live preview: every changed clause, summaries in progress
    documents = {"document_a": job["document_a"]["name"], "document_b": job["document_b"]["name"]}
    stub = types.SimpleNamespace(model=None, config=node5_config)
    probe = Node5ImpactCore(all_chunks, stub, stub, node5_config)
    skipped = {p["pair_id"] for p in pairs if probe._is_trivial(probe.build_view(p))}
    live = LiveReport(documents, all_chunks, report, pairs, skipped)
    live.preview()
    stage("preview_ready", changes=live.total)

    # Node 5 models: Critic E4B -> E2B on GPU 1; Impact Agent E4B on GPU 0 after freeing the Node 3 model
    stage("node_5_loading_agents")
    import gc
    critic_model, critic_tokenizer = None, None
    if gpus >= 2:
        for name in CRITIC_BASE_MODELS:
            try:
                critic_model, critic_tokenizer = load_critic_model(
                    base_model=name, device_index=1, checkpoint_path=None,
                    max_seq_length=node5_config.max_seq_length, hf_token=token)
                print("Critic:", name)
                break
            except Exception as e:
                print(f"Critic {name} could not be loaded on GPU 1:", str(e)[:300])
                critic_model = None
    if critic_model is None:
        critic_model = model
        print("Critic shares the Impact Agent's model (sequential mode).")
    critic_tokenizer = critic_tokenizer or tokenizer

    impact_model, impact_tokenizer = model, tokenizer
    if IMPACT_BASE_MODEL and critic_model is not model:
        impact_model = None
        del extractor, aligner, verifier, model
        gc.collect()
        torch.cuda.empty_cache()
        try:
            impact_model, tok = load_agent_model(base_model=IMPACT_BASE_MODEL, device_index=0,
                                                 max_seq_length=node5_config.max_seq_length, hf_token=token)
            impact_tokenizer = tok or tokenizer
            print("Impact Agent:", IMPACT_BASE_MODEL)
        except Exception as e:
            print(f"Impact model {IMPACT_BASE_MODEL} could not be loaded:", str(e)[:300])
            gc.collect()
            torch.cuda.empty_cache()
            impact_model, impact_tokenizer = critic_model, critic_tokenizer

    # Node 5
    impact_agent = ImpactAgent(impact_model, impact_tokenizer, node5_config)
    critic_agent = CriticAgent(critic_model, critic_tokenizer, node5_config)
    core = Node5ImpactCore(all_chunks, impact_agent, critic_agent, node5_config)

    # Warm-up (like Test A in the notebook): the first generation compiles shared
    # torch code. Doing it in two threads at once fails ("FX to symbolically trace
    # a dynamo-optimized function"), so each model runs two pairs here first, one
    # at a time. Two pairs of different lengths, so later lengths need no recompile.
    if core.parallel:
        stage("node_5_warmup")
        both = [p for p in pairs if p.get("source") and p.get("target")]
        for p in (both or pairs)[:2]:
            try:
                view = core.build_view(p)
                critic_agent.check(view, impact_agent.write(view)["summary"])
            except Exception as e:
                print("warm-up:", type(e).__name__, str(e)[:200])

    stage("node_5_impact", pairs=len(pairs), parallel=core.parallel)
    node5_checkpoint = f"{out_dir}/node5_results.jsonl"
    try:
        node5_output = run_node5(core, pairs, node5_checkpoint, live)
    except RuntimeError as e:
        if not core.parallel or not re.search(r"dynamo|FX|symbolic", str(e)):
            raise
        # Same clash despite the warm-up: continue one at a time; finished pairs
        # are read back from the checkpoint, not redone
        print("Parallel Node 5 stopped (torch compile clash); continuing sequentially:", str(e)[:200])
        core.parallel = False
        stage("node_5_impact", pairs=len(pairs), parallel=False)
        node5_output = run_node5(core, pairs, node5_checkpoint, live)
    print("Node 5 status counts:", node5_output["counts"], "| seconds:", node5_output["seconds"])
    # Every attempt of every pair (summary, checks, Critic verdict and reason): for the laptop
    if os.path.exists(node5_checkpoint):
        shutil.copyfile(node5_checkpoint, f"{OUT}/node5_results.jsonl")

    # Node 6
    stage("node_6_report")
    final_report = ReportAssembler(
        documents=documents,
        all_chunks=all_chunks,
        node3_report=report,
    ).add_many(node5_output).build()
    final_report["job"] = {"job_id": job["job_id"], "clauselens_commit": commit}
    save_report(final_report, f"{OUT}/report.json")
    save_markdown(final_report, f"{OUT}/report.md")
    save_ui_data(final_report, f"{OUT}/ui_data.json")
    print(final_report["overview"]["headline"])
    stage("done", headline=final_report["overview"]["headline"])


try:
    run()
except Exception as e:
    traceback.print_exc()
    stage("error", error=f"{type(e).__name__}: {e}"[:2000])
