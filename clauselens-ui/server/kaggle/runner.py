# ============================================================================
# ClauseLens — Kaggle runner (accelerator: GPU T4 x2, internet on)
#
# Pushed to Kaggle by clauselens-ui (server/kaggle.js) for every comparison.
# Only the Kaggle side lives here: it reads the two uploaded PDFs from the
# attached "clauselens-input" dataset, clones ClauseLens, installs the libraries
# (pipeline/install.py) and calls the ClauseLens pipeline (pipeline.run_pipeline,
# Nodes 1-6). Results go to /kaggle/working:
#
#     status.json          job id, stage, error (always written)
#     report.json          the Node 6 report
#     report.md            the report as Markdown
#     ui_data.json         the report in the shape the UI reads
#     node5_results.jsonl  every Node 5 attempt (summaries, checks, verdicts)
#
# Live results: the pipeline's on_preview / on_result hooks print the report as
# it fills in, as "[ClauseLensData ...]" log lines (base64 JSON in 8 KB pieces);
# "[ClauseLens] <stage>" lines are progress. The laptop follows the log live.
#
# Do not edit this file on Kaggle: the next comparison overwrites it.
# Edit clauselens-ui/server/kaggle/runner.py instead.
# ============================================================================

import base64
import glob
import json
import os
import shutil
import subprocess
import sys
import time
import traceback

# Must be set BEFORE torch initializes CUDA
os.environ["PYTORCH_CUDA_ALLOC_CONF"] = "expandable_segments:True"

OUT = "/kaggle/working"
WORK = "/tmp/clauselens"                 # the repo, kept out of the job output
REPO_PATH = f"{WORK}/ClauseLens"
REPO_URL = "https://github.com/Rhivu10/ClauseLens.git"
REPO_BRANCH = "main"     # the job file can name another branch (CLAUSELENS_REPO_BRANCH in the UI)

JOB = {"job_id": None}
STARTED = time.time()
EMIT = {"seq": 0}


def stage(name, **extra):
    """Progress marker for the UI (read from the Kaggle log) + status.json."""
    print(f"[ClauseLens] {name} {json.dumps({'job_id': JOB['job_id'], **extra})}", flush=True)
    status = {"job_id": JOB["job_id"], "stage": name, "seconds": round(time.time() - STARTED), **extra}
    with open(f"{OUT}/status.json", "w", encoding="utf-8") as fh:
        json.dump(status, fh, ensure_ascii=False, indent=2)


def emit_data(kind, obj):
    """Data for the live page, read from the log: base64 JSON in 8 KB lines."""
    obj = {"job_id": JOB["job_id"], **obj}            # the laptop ignores data from other runs
    blob = base64.b64encode(json.dumps(obj, ensure_ascii=False).encode("utf-8")).decode("ascii")
    parts = [blob[i:i + 8000] for i in range(0, len(blob), 8000)] or [""]
    EMIT["seq"] += 1
    for n, part in enumerate(parts, 1):
        print(f"[ClauseLensData {kind} {EMIT['seq']} {n}/{len(parts)}] {part}", flush=True)


def sh(*cmd):
    subprocess.check_call(list(cmd))


def find_job():
    hits = glob.glob("/kaggle/input/**/clauselens_job.json", recursive=True)
    if not hits:
        raise FileNotFoundError("clauselens_job.json not found: attach the clauselens-input dataset.")
    path = hits[0]
    job = json.load(open(path, encoding="utf-8"))
    folder = os.path.dirname(path)
    for side in ("document_a", "document_b"):
        job[side]["path"] = os.path.join(folder, job[side]["file"])
        if not os.path.exists(job[side]["path"]):
            raise FileNotFoundError(f"{job[side]['file']} is missing from the clauselens-input dataset.")
    return job


def find_checkpoint():
    """The CUAD LoRA adapter: in the cloned repo, or an attached Kaggle dataset."""
    repo_copy = f"{REPO_PATH}/Model Finetuning/checkpoints/checkpoint-2091"
    if os.path.exists(f"{repo_copy}/adapter_model.safetensors"):
        return repo_copy
    hits = sorted(glob.glob("/kaggle/input/**/adapter_config.json", recursive=True),
                  key=lambda p: ("checkpoint-2091" not in p, p))
    if not hits:
        raise FileNotFoundError("CUAD LoRA adapter not found in the repo (Model Finetuning/checkpoints/"
                                "checkpoint-2091) or in an attached Kaggle dataset.")
    return os.path.dirname(hits[0])


def hf_token():
    try:
        from kaggle_secrets import UserSecretsClient
        return UserSecretsClient().get_secret("HF-Token")
    except Exception:
        return None                       # the unsloth/* models are public


def clone_repo(branch=REPO_BRANCH):
    os.makedirs(WORK, exist_ok=True)
    if os.path.exists(REPO_PATH):
        shutil.rmtree(REPO_PATH)
    sh("git", "clone", "-q", "--depth", "1", "-b", branch, REPO_URL, REPO_PATH)
    sys.path.insert(0, REPO_PATH)
    return subprocess.check_output(["git", "-C", REPO_PATH, "log", "--oneline", "-1"], text=True).strip()


def run():
    job = find_job()
    JOB["job_id"] = job["job_id"]
    stage("started", files=[job["document_a"]["file"], job["document_b"]["file"]])

    stage("installing")
    commit = clone_repo(job.get("repo_branch") or REPO_BRANCH)
    print("ClauseLens commit:", commit, flush=True)
    sh(sys.executable, f"{REPO_PATH}/pipeline/install.py")

    from pipeline import PipelineConfig, run_pipeline       # imports Unsloth first
    import torch
    torch._dynamo.config.recompile_limit = 64
    gpus = torch.cuda.device_count()
    print("GPUs:", [torch.cuda.get_device_name(i) for i in range(gpus)], flush=True)
    if gpus == 0:
        raise RuntimeError("No GPU: set the notebook accelerator to 'GPU T4 x2'.")

    config = PipelineConfig(
        checkpoint_path=find_checkpoint(),
        hf_token=hf_token(),
        document_names=(job["document_a"]["name"], job["document_b"]["name"]),
        output_dir=OUT,
    )
    state = run_pipeline(
        job["document_a"]["path"], job["document_b"]["path"], config,
        on_stage=lambda name, **info: None if "seconds" in info else stage(name, **info),
        on_preview=lambda payload: emit_data("preview", payload),
        on_result=lambda payload: emit_data("result", payload),
    )
    headline = state["report"]["overview"]["headline"]
    print(headline, "| seconds per node:", state["timings"], flush=True)
    stage("done", headline=headline)


try:
    run()
except Exception as e:
    traceback.print_exc()
    stage("error", error=f"{type(e).__name__}: {e}"[:2000])
